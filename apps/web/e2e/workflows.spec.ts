test('키 없는 파일 업로드, 검색, 대기 작업 취소', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '새 회의 업로드', exact: true }).click()
  await page.getByLabel('회의 제목', { exact: true }).fill('업로드 확인 회의')
  const wav = Buffer.alloc(44 + 32000)
  wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8); wav.writeUInt32LE(16, 16)
  wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22); wav.writeUInt32LE(16000, 24); wav.writeUInt32LE(32000, 28)
  wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(32000, 40)
  const transfer = await page.evaluateHandle(bytes => {
    const value = new DataTransfer()
    value.items.add(new File([new Uint8Array(bytes)], '회의 음성.wav', { type: 'audio/wav' }))
    return value
  }, Array.from(wav))
  await page.locator('.upload-form').dispatchEvent('drop', { dataTransfer: transfer })
  await transfer.dispose()
  await page.getByRole('button', { name: '업로드하고 처리 시작', exact: true }).click()
  const row = page.locator('.meeting-row').filter({ hasText: '업로드 확인 회의' })
  await expect(row).toContainText('대기', { timeout: 10000 })
  await row.getByRole('button', { name: '취소', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '취소', exact: true }).click()
  await expect(row).toContainText('대기')
  await row.getByRole('button', { name: '취소', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '확인', exact: true }).click()
  await expect(row).toContainText('취소됨')
  await page.getByLabel('제목·본문 검색', { exact: true }).fill('업로드 확인')
  await expect(page.locator('.meeting-row')).toHaveCount(1)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

