test('실제 MP4 브라우저 업로드와 잘못된 파일 오류', async ({ page }) => {
  const directory = mkdtempSync(join(tmpdir(), 'minutes-video-'))
  try {
    const path = join(directory, '영상 회의.mp4')
    execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'color=c=black:s=32x32:d=1',
      '-f', 'lavfi', '-i', 'sine=frequency=440:duration=1', '-c:v', 'mpeg4', '-c:a', 'aac', '-shortest', path])
    await page.goto('/')
        await page.getByRole('button', { name: '새 회의 업로드', exact: true }).click()
    await page.getByLabel('회의 제목', { exact: true }).fill('영상 업로드 확인')
    await page.getByLabel('음성 또는 영상 파일', { exact: true }).setInputFiles(path)
    await page.getByRole('button', { name: '업로드하고 처리 시작', exact: true }).click()
    await expect(page.locator('.meeting-row').filter({ hasText: '영상 업로드 확인' })).toContainText('대기', { timeout: 10000 })
    await page.getByRole('button', { name: '새 회의 업로드', exact: true }).click()
    await page.getByLabel('회의 제목', { exact: true }).fill('거부할 파일')
    await page.getByLabel('음성 또는 영상 파일', { exact: true }).setInputFiles({ name: 'unsupported.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('not media') })
    await page.getByRole('button', { name: '업로드하고 처리 시작', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('지원하는 미디어 파일')
  } finally { rmSync(directory, { recursive: true, force: true }) }
})
